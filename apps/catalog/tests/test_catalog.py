import io

import pytest
from PIL import Image
from django.core.files.uploadedfile import SimpleUploadedFile
from rest_framework.test import APIClient

from apps.accounts.models import User
from apps.catalog.models import Category, Product


def make_test_image():
    buf = io.BytesIO()
    Image.new('RGB', (10, 10), color='red').save(buf, format='PNG')
    buf.seek(0)
    return SimpleUploadedFile('test.png', buf.read(), content_type='image/png')


@pytest.fixture
def api_client():
    return APIClient()


@pytest.fixture
def staff_user():
    return User.objects.create_user(username='staff', email='staff@example.com', password='x', is_staff=True)


@pytest.fixture
def customer():
    return User.objects.create_user(username='customer', email='customer@example.com', password='x')


@pytest.mark.django_db
def test_category_slug_autogenerated_and_unique():
    c1 = Category.objects.create(name='Sillas')
    c2 = Category.objects.create(name='Sillas')  # mismo nombre -> el slug debe desambiguarse

    assert c1.slug == 'sillas'
    assert c2.slug != c1.slug


@pytest.mark.django_db
def test_anonymous_can_read_but_not_write(api_client):
    resp = api_client.get('/api/catalog/products/')
    assert resp.status_code == 200

    resp = api_client.post('/api/catalog/products/', {'title': 'x'})
    assert resp.status_code == 401  # no autenticado, no solo "sin permiso"


@pytest.mark.django_db
def test_authenticated_non_staff_cannot_write(api_client, customer):
    category = Category.objects.create(name='Mesas')
    api_client.force_authenticate(user=customer)

    resp = api_client.post('/api/catalog/products/', {
        'title': 'Mesa ratona', 'price': '100.00', 'category': category.id,
        'stock': 5, 'image': make_test_image(),
    }, format='multipart')

    assert resp.status_code == 403


@pytest.mark.django_db
def test_staff_can_create_and_edit_product_including_rating(api_client, staff_user):
    category = Category.objects.create(name='Sofás')
    api_client.force_authenticate(user=staff_user)

    resp = api_client.post('/api/catalog/products/', {
        'title': 'Sofá 3 cuerpos', 'price': '999.99', 'category': category.id,
        'stock': 3, 'image': make_test_image(),
    }, format='multipart')
    assert resp.status_code == 201
    product_id = resp.data['id']

    resp = api_client.patch(f'/api/catalog/products/{product_id}/', {
        'rating_rate': '4.50', 'rating_count': 12,
    })
    assert resp.status_code == 200
    assert resp.data['rating_rate'] == '4.50'
    assert resp.data['rating_count'] == 12


@pytest.mark.django_db
def test_filter_by_category_and_price_range(api_client):
    cat_a = Category.objects.create(name='Categoria A')
    cat_b = Category.objects.create(name='Categoria B')
    cheap = Product.objects.create(title='Barato', price='10.00', category=cat_a, image=make_test_image())
    Product.objects.create(title='Caro', price='500.00', category=cat_a, image=make_test_image())
    Product.objects.create(title='Otra categoria', price='10.00', category=cat_b, image=make_test_image())

    resp = api_client.get(f'/api/catalog/products/?category={cat_a.id}&max_price=100')
    ids = [p['id'] for p in resp.data['results']]

    assert resp.status_code == 200
    assert ids == [cheap.id]
